#!/usr/bin/env python3
"""Generate the browsable .stk/.flp index from active input statements."""
import json
from pathlib import Path
import re
from run_case import ROOT, floorplans, resolve_floorplan, uncomment

def references(path):
    s = str(path)
    if s.startswith('models/co-planar'): return ['stratum','plate','glass']
    if s.startswith('models/dual-side'): return ['stratum','plate','air']
    if s.startswith('models/interlayer'): return ['stratum','hyflex','glass-cooling','plate']
    if s.startswith('models/panel') or s.startswith('demo/inputs'): return ['panel','stratum','plate','pic']
    if 'H100' in s or 'h100-power' in s: return ['ttv']
    if 'H200' in s: return ['plate']
    if 'Stratum-S' in s: return ['stratum','plate']
    if 'pic-sohrab' in s or '/photonic/' in s: return ['pic']
    if 'silicon-interlayer' in s: return ['silicon-cooling']
    if 'cu-pillar' in s: return ['glass-cooling']
    return ['hyflex','glass-cooling','hausen']

def main():
    cases=[];used={}
    for folder in ('models','validation','demo/inputs'):
        for stk in sorted((ROOT/folder).rglob('*.stk')):
            path=stk.relative_to(ROOT).as_posix();txt=uncomment(stk.read_text())
            flps=[resolve_floorplan(stk,r) for r in floorplans(stk)]
            power=0.;samples=set()
            for f in flps:
                for q in re.findall(r'power values\s+([^;]+);',uncomment(f.read_text())):
                    vals=[float(x) for x in q.replace(',',' ').split()];power+=vals[0];samples.add(len(vals))
                used.setdefault(f.relative_to(ROOT).as_posix(),[]).append(path)
            grid=re.search(r'cell length\s+([\d.]+),\s*width\s+([\d.]+)',txt)
            boundary=[]
            for name, block in re.findall(r'((?:top|bottom) heat sink)\s*:\s*(.*?)(?=dimensions\s*:|material\s+|(?:top|bottom) heat sink\s*:|microchannel|layer\s+)',txt,re.S):
                h=re.search(r'heat transfer coefficient\s+([\d.eE+\-]+)',block)
                t=re.search(r'\btemperature\s+([\d.eE+\-]+)',block)
                if h and t:boundary.append(f'{name.split()[0]} h={h[1]}, T={t[1]} K')
            cases.append({'stack':path,'floorplans':[p.relative_to(ROOT).as_posix() for p in flps],
                'references':references(path),'grid_um':list(grid.groups()) if grid else [],
                'boundaries':boundary,'first_sample_power_W':round(power,6),'power_samples':sorted(samples)})
    (ROOT/'provenance/cases.json').write_text(json.dumps(cases,indent=2)+'\n')
    lines=['# Stack and floorplan index','','Generated by `python3 tools/catalog.py`. Values below come from active statements, with comments removed. Power is the sum of the first sample in every source floorplan; for transient cases it is the warm-up load, not the window peak. Cooling coefficients use W/µm²K. Each reference link explains the architecture or primitive; it does not assert that every historical variant is a held-out validation.','','| Stack | Floorplans | Grid (µm) | Power (W) | Boundaries | Academic sources |','|---|---|---|---:|---|---|']
    for c in cases:
        link=lambda p:f'[{Path(p).name}](../{p})'
        refs=', '.join(f'[{r}](references.md#{r})' for r in c['references'])
        lines.append('| '+ ' | '.join([link(c['stack']),'<br>'.join(map(link,c['floorplans'])),' × '.join(c['grid_um']),str(c['first_sample_power_W']),'<br>'.join(c['boundaries']) or 'Embedded cooling; see stack',refs])+' |')
    lines+=['','## Every floorplan','','Includes geometry variants and generator seeds that are not referenced by a released stack.','','| Floorplan | Used by | Academic sources |','|---|---|---|']
    for folder in ('models','validation','demo/inputs'):
        for f in sorted((ROOT/folder).rglob('*.flp')):
            p=f.relative_to(ROOT).as_posix();users=used.get(p,[])
            refs=', '.join(f'[{r}](references.md#{r})' for r in references(p))
            lines.append(f'| [{p}](../{p}) | '+('<br>'.join(f'[{Path(x).name}](../{x})' for x in users) or 'Archived geometry / generator input')+f' | {refs} |')
    (ROOT/'docs/case-index.md').write_text('\n'.join(lines)+'\n')
    print(f'Indexed {len(cases)} stacks')

if __name__ == '__main__':main()
