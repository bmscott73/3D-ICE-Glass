#!/usr/bin/env python3
"""
gen_pan_flps.py -- PanAgretti row neighbourhood: [HBM][xPU] [decode A] [decode B]
Built to PanAgretti Fig. 2(b) (memory-logic-PIC organisation) and Fig. 3 (row layout).

CANVAS 89800 x 24400 um, 200 um grid. 89800 = 200 x 449 with 449 ODD, so a 200/200 um
4rm cavity would tile the length exactly if a cooling variant ever needs one.
Waveguide corridor runs along x at the low-y edge; laser is off-panel to the west.

VERTICAL, per node (top -> bottom):
  cold plate | 2 mm Cu | TIM | M3D-DRAM tiles | Cu-Cu hybrid bond | LOGIC DIE (NMP + DRAM
  controllers + EIC drivers) | Cu-Cu bumps | PIC (in glass cavity) | PIC bumps | GIP RDL +
  SiN WG plane | GIP TGV field | glass core | (GIP bumps: adiabatic)
No auxiliary die: DRAM is hybrid-bonded directly to the logic die (PanAgretti Sec. III).

POWER (GLM-4.5 decode, ctx 65536, BS 320, 1 GHz; per node from decode.csv):
  avg_dram      136.23 W -> 4 tiles x 34.06 W (34.1 W/cm^2)
  avg_compute   156.67 W -> NMP logic
  avg_transfer   16.58 W -> split: PIC heaters 3.05 W (Tianqi's interleaver + modulator +
                           filter thermal budget, load-independent) + EIC 13.53 W (Tx driver,
                           Rx TIA, 6.1 W static) IN THE LOGIC DIE per PanAgretti Sec. III
  logic die total 170.20 W = 42.55 W/cm^2 ; PIC 3.05 W / 16 mm^2 = 19.1 W/cm^2
Prefill node: xPU 300 W (A6000-class 628 mm^2; NOTE PanAgretti Table I lists 2 PFLOPs /
  192 GB HBM = B200-class, flagged), HBM3 20 W, prefill PIC 3.05 W (EIC inside the xPU TDP).
"""
CX, CY, GRID = 89800, 24400, 200
P_XPU, P_HBM, P_DRAM, P_NMP, P_EIC, P_PIC = 300.0, 20.0, 34.06, 156.67, 13.53, 3.05

HBM  = (1000, 6600, 11000, 11000)
XPU  = (13000, 1000, 28000, 22400)
NODE = {"A": 43000, "B": 67000}         # NMP-MEM 22x22 region origin x; y 1200..23200
NY = 1200
def dram(x0):  # 2x2 quad, 10x10 mm, 400 um inset
    return [(f"DRAM_{i}", x0+dx, NY+dy, 10000, 10000) for i,(dx,dy) in
            enumerate([(400,400),(11600,400),(400,11600),(11600,11600)])]
def logic(x0): return (x0+1000, NY+1000, 20000, 20000)
def pic(x0):   return (x0+9000, NY+1000, 4000, 4000)      # under the logic die, low-y edge
PIC_X = (25000, 1000, 4000, 4000)                         # under the xPU, low-y edge

def tile(act):
    ys = sorted({0, CY} | {a[2] for a in act} | {a[2]+a[4] for a in act})
    for a in act:
        for y0,y1 in zip(ys,ys[1:]):
            i = max(0, min(a[2]+a[4],y1)-max(a[2],y0)); assert i in (0,y1-y0), f"{a[0]} straddles"
    out,n = [],0
    for y0,y1 in zip(ys,ys[1:]):
        row = sorted([a for a in act if a[2]<=y0 and a[2]+a[4]>=y1], key=lambda a:a[1]); x=0
        for a in row:
            if a[1]>x: out.append((f"FILL_{n}",x,y0,a[1]-x,y1-y0,0.0)); n+=1
            x=a[1]+a[3]
        if x<CX: out.append((f"FILL_{n}",x,y0,CX-x,y1-y0,0.0)); n+=1
    return out+list(act)
def check(b,p,lab):
    ar=0
    for nm,x,y,w,h,q in b:
        assert 0<=x and 0<=y and x+w<=CX and y+h<=CY and w>0 and h>0, f"{lab}/{nm} bounds"
        for v in (x,y,w,h): assert v%GRID==0, f"{lab}/{nm} off grid {v}"
        ar+=w*h
    for i,a in enumerate(b):
        for c in b[i+1:]:
            if a[1]<c[1]+c[3] and c[1]<a[1]+a[3] and a[2]<c[2]+c[4] and c[2]<a[2]+a[4]:
                raise AssertionError(f"{lab}: overlap {a[0]}/{c[0]}")
    assert ar==CX*CY, f"{lab}: tiling {ar}!={CX*CY}"
    assert abs(sum(x[5] for x in b)-p)<1e-6, f"{lab}: power {sum(x[5] for x in b):.3f}!={p:.3f}"
def write(path,hdr,b,p):
    check(b,p,path)
    with open(path,"w") as f:
        f.write(hdr)
        for nm,x,y,w,h,q in b: f.write(f"{nm} :\n    position  {x}, {y} ;\n    dimension {w}, {h} ;\n    power values {q:g} ;\n\n")
H="// Generated by gen_pan_flps.py -- regenerate, do not hand-edit.\n\n"

def main():
    act=[("XPU",)+XPU+(P_XPU,),("HBM",)+HBM+(P_HBM,)]
    for t,x0 in NODE.items(): act+=[(f"{n}_{t}",x,y,w,h,P_DRAM) for n,x,y,w,h in dram(x0)]
    write("pan_mem.flp","// pan_mem.flp -- TOP tier under the cold plate: prefill xPU + HBM3 (west) and eight\n"
          "// M3D-DRAM tiles in two 2x2 quads (decode nodes A, B). DRAM = avg_dram_power / 4.\n"+H,
          tile(act), P_XPU+P_HBM+8*P_DRAM)
    act=[]
    for t,x0 in NODE.items():
        lx,ly,lw,lh=logic(x0); act.append((f"LOGIC_{t}",lx,ly,lw,lh,P_NMP+P_EIC))
    write("pan_logic.flp","// pan_logic.flp -- LOGIC DIE tier: NMP compute + DRAM controllers + EIC drivers in ONE\n"
          "// die per PanAgretti Sec. III. 20x20 mm at 156.67 (NMP) + 13.53 (EIC) = 170.20 W = 42.6 W/cm^2.\n"
          "// Hybrid-bonded directly to the DRAM quad above; no auxiliary die.\n"+H, tile(act), 2*(P_NMP+P_EIC))
    act=[("PIC_X",)+PIC_X+(P_PIC,)]
    for t,x0 in NODE.items():
        px,py,pw,ph=pic(x0); act.append((f"PIC_{t}",px,py,pw,ph,P_PIC))
    write("pan_pic_die.flp","// pan_pic_die.flp -- PIC TIER: separately fabricated PICs EMBEDDED in glass cavities\n"
          "// BENEATH each logic die (PanAgretti Fig. 2b), 4x4 mm, 3.05 W heater/tuning power each\n"
          "// (interleaver 0.90 + modulator 1.48 + filter 0.67, load-independent). Placed at the\n"
          "// logic die's low-y edge so the PIC coupler faces the waveguide corridor. The layer\n"
          "// material is GLASS (cavity fill covers 99% of it); the PIC's own silicon is thus\n"
          "// under-spread by <=1 K, conservative. Max-min over each PIC block = ring-bank spread.\n"+H,
          tile(act), 3*P_PIC)
    act=[("WG_CORRIDOR",0,600,CX,400,0.0)]
    for nm,(x,y,w,h) in (("CPL_X",PIC_X),("CPL_A",pic(NODE["A"])),("CPL_B",pic(NODE["B"]))):
        act.append((nm,x,1000,w,200,0.0))          # coupler strip between corridor and PIC edge
    write("pan_pic.flp","// pan_pic.flp -- GIP RDL / SiN WAVEGUIDE PLANE (glass, 0 W markers).\n"
          "//   WG_CORRIDOR  the row waveguide, y 600-1000, spanning all three nodes and passing\n"
          "//                beneath the xPU (x 13-41 mm): the crossing GlassML must survive\n"
          "//   CPL_X/A/B    coupler regions where each PIC launches into the corridor\n"
          "// Laser/comb is OFF-PANEL (PanAgretti Sec. III-A): no source block.\n"+H, tile(act), 0.0)
    tot=P_XPU+P_HBM+3*P_PIC+2*(4*P_DRAM+P_NMP+P_EIC)
    print(f"OK: 4 floorplans; package total {tot:.2f} W; canvas {CX//GRID} x {CY//GRID} cells")
if __name__=="__main__": main()
