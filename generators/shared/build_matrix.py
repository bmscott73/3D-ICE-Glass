#!/usr/bin/env python3
"""Generate water controls and 0.735/0.575 warm-loop plate endpoints.

Secondary air conductance uses the ATS 1/2/3/4 m/s resistance table over
the 39.6 x 31.8 mm engine area. Geometry and material parameters are fixed.
Use tools/generate.py matrix to supply dependencies and verify output headers.
"""
import os
OUT = "outputs-matrix"
H_WATER = 4.08e-8
H_LIQ = {"735": H_WATER*.735, "575": H_WATER*.575}
H_AIR = {g: 1/(r*39600*31800) for g,r in {"1ms":.52,"2ms":.32,"3ms":.26,"4ms":.23}.items()}
R_AIR = {"1ms":.52,"2ms":.32,"3ms":.26,"4ms":.23}

MATERIALS = """
material SILICON :
    thermal conductivity     1.30e-04 ;
    volumetric heat capacity 1.75e-12 ;
material TIM :
    thermal conductivity     4.00e-06 ;
    volumetric heat capacity 4.00e-12 ;
material COPPER :
    thermal conductivity     4.00e-04 ;
    volumetric heat capacity 3.45e-12 ;
material HYBRID_BOND :
    thermal conductivity     1.21e-04 ;
    volumetric heat capacity 2.14e-12 ;
material UBUMP_UF :
    thermal conductivity     2.00e-05 ;
    volumetric heat capacity 2.50e-12 ;
material GLASS :
    thermal conductivity     1.40e-06 ;
    volumetric heat capacity 1.60e-12 ;
material TGV_GLASS_COMPOSITE :
    thermal conductivity     1.00e-06, 1.00e-06, 7.9204e-05 ;
    volumetric heat capacity 1.96e-12 ;
"""
DIMS = """
dimensions :
    chip length 39600, width 31800 ;
    cell length 100,   width 100 ;
    non-uniform false ;
"""
LAYERS = """
layer CP_BASE_L :            // 2 mm Cu base of the PRIMARY liquid plate; h on its OUTER face
    height   2000 ;
    material COPPER ;
layer CP_BASE2_L :           // 2 mm Cu SPREADER coupling the memory tier to the air sink
    height   2000 ;
    material COPPER ;
layer TIM_L :
    height   20 ;
    material TIM ;
layer HB_L :
    height   1 ;
    material HYBRID_BOND ;
layer UBUMP_L :
    height   40 ;
    material UBUMP_UF ;
layer IPOSER_TGV_L :
    height   110 ;
    material TGV_GLASS_COMPOSITE ;
layer IPOSER_CAV_L :
    height   100 ;
    material GLASS ;
layer IPOSER_CORE_L :
    height   150 ;
    material GLASS ;

die DIE_TOP_D :
    layer  145 SILICON ;
    source   5 SILICON ;
die DIE_BOT_D :
    source   5 SILICON ;
    layer   95 SILICON ;
die PIC_PLANE_D :
    source  20 GLASS ;
die DIE_MEM_D :
    source   5 SILICON ;
    layer   95 SILICON ;
die DIE_LOGIC_D :
    source   5 SILICON ;
    layer   95 SILICON ;
"""

def sink_top(h, t):
    return f"""
top heat sink :                      // PRIMARY: direct-to-chip liquid plate, ref = coolant inlet
    heat transfer coefficient {h:.4g} ;
    temperature {t} ;
"""

def sink_bot(h, t, grade):
    return f"""
// SECONDARY: forced-air finned aluminium heat sink on the memory tier, ref = APPROACH AIR.
// h_eff is an area-normalized sink-to-air conductance (R_sa = {R_AIR[grade]} K/W on the
// 1259.28 mm^2 footprint), NOT a raw air-film coefficient. Derived from a commercial
// straight-fin sink datasheet; the explicit TIM above is retained (conservative if the
// datasheet figure already includes one). No second liquid loop, no manifold, no added pump.
// Air reference is set equal to the liquid inlet here; see README for the split-reference
// zero-power run if the two references must differ.
bottom heat sink :
    heat transfer coefficient {h:.4g} ;
    temperature {t} ;
"""

def outs(tag, dies):
    o = """
solver :
    steady ;
    initial temperature 300.0 ;
    numofcores 12 ;

output :
"""
    for d in dies:
        o += f'    Tflp( {d}, "{OUT}/{tag}_{d.lower()}_max.txt", maximum, final ) ;\n'
        o += f'    Tflp( {d}, "{OUT}/{tag}_{d.lower()}_avg.txt", average, final ) ;\n'
    o += f'    Tflp( PIC_PLANE, "{OUT}/{tag}_pic_plane_min.txt", minimum, final ) ;\n'
    for d in dies:
        o += f'    Tmap( {d}, "{OUT}/{tag}_{d.lower()}_tmap.txt", final ) ;\n'
    return o

def cp(tag, h, t, note):
    hdr = f"""// ============================================================
// {tag}.stk -- CO-PLANAR BRIDGE, warm-liquid envelope point
// {note}
// Primary h = {h:.3g} at {t} K. Offsets to other inlets are exact: T(T_in) = T + (T_in - {t}).
// Floorplans identical to static-standard (comb 0 W).
// Generated by build_matrix.py.
// ============================================================
"""
    stack = """
stack :
    layer   CP_BASE     CP_BASE_L ;
    layer   TIM_TOP     TIM_L ;
    die     DIE_TOP     DIE_TOP_D  floorplan "die_top_bridge.flp" ;
    layer   HB_IFACE    HB_L ;
    die     DIE_BOT     DIE_BOT_D  floorplan "die_bot_bridge.flp" ;
    layer   UBUMP       UBUMP_L ;
    layer   IPOSER_TGV  IPOSER_TGV_L ;
    layer   IPOSER_CAV  IPOSER_CAV_L ;
    die     PIC_PLANE   PIC_PLANE_D floorplan "pic_plane_bridge.flp" ;
    layer   IPOSER_CORE IPOSER_CORE_L ;
"""
    return hdr + MATERIALS + sink_top(h, t) + DIMS + LAYERS + stack + outs(tag, ["DIE_TOP", "DIE_BOT", "PIC_PLANE"])

def d2air(tag, h_liq, h_air, grade, t, note):
    hdr = f"""// ============================================================
// {tag}.stk -- ASYMMETRIC DUAL-SIDED (HYBRID LIQUID/AIR) COOLING, glass-separated
// {note}
// liquid plate | Cu base | TIM | xPU(+OPT_IO) | ubump | GLASS (TGV + PIC plane) | ubump
//   | NMP logic | hybrid bond | Mono3D DRAM | TIM | Cu SPREADER | forced-air heat sink
// Liquid cooling is reserved for the 260.6 W xPU/optical tier; the 144.67 W memory tier is
// evaluated on a conventional forced-air finned sink. Tests whether thermal separation and
// demand-matched cooler allocation eliminate the second liquid plate, its manifold and pump.
// Primary h = {h_liq:.3g}; secondary h_eff = {h_air:.4g} (R_sa = {R_AIR[grade]} K/W); refs {t} K.
// Generated by build_matrix.py.
// ============================================================
"""
    stack = """
stack :
    layer   CP_BASE     CP_BASE_L ;
    layer   TIM_TOP     TIM_L ;
    die     DIE_TOP     DIE_TOP_D   floorplan "die_xpu_dual.flp" ;
    layer   UBUMP       UBUMP_L ;
    layer   IPOSER_TGV  IPOSER_TGV_L ;
    layer   IPOSER_CAV  IPOSER_CAV_L ;
    die     PIC_PLANE   PIC_PLANE_D floorplan "pic_plane_dual.flp" ;
    layer   IPOSER_CORE IPOSER_CORE_L ;
    layer   UBUMP_BOT   UBUMP_L ;
    die     DIE_LOGIC   DIE_LOGIC_D floorplan "die_logic_dual.flp" ;
    layer   HB_IFACE    HB_L ;
    die     DIE_MEM     DIE_MEM_D   floorplan "die_mem_dual.flp" ;
    layer   TIM_BOT     TIM_L ;
    layer   CP_BASE2    CP_BASE2_L ;
"""
    return (hdr + MATERIALS + sink_top(h_liq, t) + sink_bot(h_air, t, grade) + DIMS + LAYERS + stack
            + outs(tag, ["DIE_TOP", "DIE_LOGIC", "DIE_MEM", "PIC_PLANE"]))

def main():
    os.makedirs("runs", exist_ok=True)
    f = {}
    # ---- 1. dual-sided with forced-air secondary, water-validated primary, 300 K refs ----
    for g, ha in H_AIR.items():
        f[f"d2air-{g}"] = d2air(f"d2air-{g}", H_WATER, ha, g, 300,
            f"Forced-air secondary, {g} grade ({R_AIR[g]} K/W). Primary = validated water plate. "
            f"Compare to d2-noplate (94.62 C) and d2-standard (52.46 C).")
    # Property-derived plate endpoints; catalogued sink conductance stays fixed.
    for k, hl in H_LIQ.items():
        note=f"Frozen water plate times {float(k)/1000:g}; common 308 K reference."
        f[f"cp-{k}"] = cp(f"cp-{k}", hl, 308, note)
        for grade, ha in H_AIR.items():
            tag=f"d2air-{grade}-{k}"
            f[tag] = d2air(tag,hl,ha,grade,308,note)
    for t, txt in f.items():
        open(f"runs/{t}.stk", "w").write(txt)
    print(f"wrote {len(f)} stacks to runs/: " + " ".join(f))

if __name__ == "__main__":
    main()
