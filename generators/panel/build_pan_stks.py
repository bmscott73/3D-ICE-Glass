#!/usr/bin/env python3
"""build_pan_stks.py -- PanAgretti row neighbourhood stacks (Fig. 2b vertical order)."""
import os
OUT="outputs-pan"
MAT="""
material SILICON :
    thermal conductivity     1.30e-04 ;
    volumetric heat capacity 1.75e-12 ;
material TIM :
    thermal conductivity     4.00e-06 ;
    volumetric heat capacity 4.00e-12 ;
material COPPER :
    thermal conductivity     4.00e-04 ;
    volumetric heat capacity 3.45e-12 ;
material HYBRID_BOND :               // Cu-Cu hybrid bond, DRAM <-> logic
    thermal conductivity     1.21e-04 ;
    volumetric heat capacity 2.14e-12 ;
material UBUMP_UF :                  // Cu-Cu bumps + underfill, logic <-> PIC and PIC <-> glass
    thermal conductivity     2.00e-05 ;
    volumetric heat capacity 2.50e-12 ;
material GLASS :
    thermal conductivity     1.40e-06 ;
    volumetric heat capacity 1.60e-12 ;
material TGV_GLASS_COMPOSITE :       // GIP TGV field, volume-fraction orthotropic
    thermal conductivity     1.00e-06, 1.00e-06, 7.9204e-05 ;
    volumetric heat capacity 1.96e-12 ;
"""
DIMS="""
dimensions :
    chip length 89800, width 24400 ;
    cell length 200,   width 200 ;
    non-uniform false ;
"""
LAY="""
layer CP_BASE_L :
    height   2000 ;
    material COPPER ;
layer TIM_L :
    height   20 ;
    material TIM ;
layer HB_L :                  // EIC Cu-Cu ubump / hybrid bond (Fig. 2b)
    height   1 ;
    material HYBRID_BOND ;
layer CUCU_PIC_L :            // Cu-Cu bumps, logic die -> embedded PIC
    height   20 ;
    material UBUMP_UF ;
layer PIC_BUMP_L :            // PIC bumps -> GIP
    height   40 ;
    material UBUMP_UF ;
layer IPOSER_TGV_L :          // GIP TGV field
    height   110 ;
    material TGV_GLASS_COMPOSITE ;
layer IPOSER_CORE_L :
    height   150 ;
    material GLASS ;

die DIE_MEM_D :               // M3D-DRAM tiles + xPU + HBM
    layer  145 SILICON ;
    source   5 SILICON ;
die DIE_LOGIC_D :             // NMP + DRAM controllers + EIC drivers, one die
    source   5 SILICON ;
    layer   95 SILICON ;
die DIE_PIC_D :               // PIC chips in glass cavities; layer material GLASS (see flp header)
    source   5 GLASS ;
    layer   95 GLASS ;
die PIC_PLANE_D :             // GIP RDL + SiN waveguide plane
    source  20 GLASS ;
"""
def outs(tag):
    o=f"""
solver :
    steady ;
    initial temperature 300.0 ;
    numofcores 12 ;

output :
"""
    for d in ("DIE_MEM","DIE_LOGIC","DIE_PIC","PIC_PLANE"):
        for m in ("maximum","average","minimum"):
            o+=f'    Tflp( {d}, "{OUT}/{tag}_{d.lower()}_{m[:3]}.txt", {m}, final ) ;\n'
    for d in ("DIE_MEM","DIE_LOGIC","DIE_PIC","PIC_PLANE","CP_BASE"):
        o+=f'    Tmap( {d}, "{OUT}/{tag}_{d.lower()}_tmap.txt", final ) ;\n'
    return o
def stk(tag,h,t,note,coplanar=False):
    hdr=f"""// ============================================================
// {tag}.stk -- PanAgretti row neighbourhood: [HBM][xPU] [decode A] [decode B]
// {note}
// PanAgretti Fig. 2b vertical order:
//   cold plate | 2 mm Cu | TIM | DIE_MEM (M3D-DRAM x8, xPU, HBM) | Cu-Cu hybrid bond
//   | DIE_LOGIC (NMP + controllers + EIC drivers) | Cu-Cu bumps | DIE_PIC (PICs in glass
//   cavities BENEATH the logic dies) | PIC bumps | GIP RDL + SiN WG plane | GIP TGV | glass
// 449 x 122 x 14 layers = 766,892 nodes. Package 942.03 W. Plate h = {h:.4g}, ref {t} K.
// Not resolved (homogenised): EIC/PIC TSVs, individual bumps. Not mowarmed: off-panel
// laser, the other 61 decode nodes / 7 xPUs (adiabatic side walls = periodic neighbours).
// Generated by build_pan_stks.py.
// ============================================================
"""
    sink=f"""
top heat sink :
    heat transfer coefficient {h:.4g} ;
    temperature {t} ;
"""
    pic_flp = "pan_pic_die_coplanar.flp" if coplanar else "pan_pic_die.flp"
    stack=f"""
stack :
    layer   CP_BASE     CP_BASE_L ;
    layer   TIM_TOP     TIM_L ;
    die     DIE_MEM     DIE_MEM_D    floorplan "pan_mem.flp" ;
    layer   HB_DRAM     HB_L ;
    die     DIE_LOGIC   DIE_LOGIC_D  floorplan "pan_logic.flp" ;
    layer   CUCU_PIC    CUCU_PIC_L ;
    die     DIE_PIC     DIE_PIC_D    floorplan "{pic_flp}" ;
    layer   PIC_BUMP    PIC_BUMP_L ;
    die     PIC_PLANE   PIC_PLANE_D  floorplan "pan_pic.flp" ;
    layer   IPOSER_TGV  IPOSER_TGV_L ;
    layer   IPOSER_CORE IPOSER_CORE_L ;
"""
    return hdr+MAT+sink+DIMS+LAY+stack+outs(tag)
def main():
    os.makedirs("runs",exist_ok=True)
    f={}
    f["pan-std"]  = stk("pan-std", 4.08e-8, 300, "STANDARD: validated water plate, 26.85 C. The baseline row.")
    f["pan-warm"] = stk("pan-warm", 4.08e-8*0.735, 308, "WARM LOOP: 35 C inlet, PG25-30 (h x0.735). 45 C follows by exact +10 K offset.")
    # NOTE: a co-planar-PIC control does not fit this row: a 4x4 mm PIC cannot sit beside a
    # 20x20 mm logic die inside a 22x22 mm node, and the inter-node gaps are 2 mm. That
    # geometric fact is itself why PanAgretti embeds the PIC beneath the logic die. The
    # relevant readout is therefore DIE_PIC max vs LOGIC max (the drop across the Cu-Cu bond)
    # and PIC max-min (ring-bank spread), not a beside/beneath comparison.
    for t,txt in f.items(): open(f"runs/{t}.stk","w").write(txt)
    print("wrote",len(f),"stacks")
if __name__=="__main__": main()
