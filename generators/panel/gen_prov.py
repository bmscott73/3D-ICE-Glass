#!/usr/bin/env python3
"""
gen_prov.py -- provisioning ladder for the panel-scale LLM row.
Three power levels, same geometry, from the performance table and the replayed trace:

  level          per node   DRAM/tile   logic (NMP+EIC)   PIC    package
  trace floor      309.5       34.06         170.20       3.05     942.03   <- pan-std (already run)
  trace mean       398.3       41.31         230.00       3.05    1119.63   <- pan-wl
  config TDP       519.0       51.67         309.25       3.05    1361.01   <- pan-tdp

CHANNELS DO NOT SCALE TOGETHER. From BS 320 to BS ~960 the DRAM term grows x1.21 and the
compute term x1.41, while the I/O term FALLS x0.69 (16.6 -> 11.5 W) because the all-to-all
payload amortises over a longer decode interval. Uniform scaling of the node total is
therefore wrong; each channel is taken from its own table column.
  trace mean   = GLM-4.5, ctx 65536, 1000 TFLOPS, BS interpolated to ~960 (the replayed
                 trace's time-weighted mean active-session count)
  config TDP   = max over BS (320-163840) x TFLOPS (100-2000) at the same model and context
PIC is held at 3.05 W at every level: thermal tuning is load-independent.
xPU 300 W and HBM 20 W are constant (no prefill trace available).
"""
import re, os
LEVELS = {"wl":  dict(dram=41.31, logic=230.00, node=398.3, label="trace mean (BS~960)"),
          "tdp": dict(dram=51.67, logic=309.25, node=519.0, label="configuration TDP (BS 163840, 2 PFLOPS)")}
P_PIC, P_XPU, P_HBM = 3.05, 300.0, 20.0

def parse(p):
    return re.findall(r"^(\w+)\s*:\s*\n\s*position\s+(\d+),\s*(\d+)\s*;\s*\n\s*dimension\s+(\d+),\s*(\d+)\s*;"
                      r"\s*\n\s*power values\s+([\d.eE+-]+)\s*;", open(p).read(), re.M)

def write(path, hdr, blocks, pw):
    tot = 0.0
    with open(path, "w") as f:
        f.write(hdr)
        for nm, x, y, w, h, _ in blocks:
            q = pw(nm); tot += q
            f.write(f"{nm} :\n    position  {x}, {y} ;\n    dimension {w}, {h} ;\n    power values {q:g} ;\n\n")
    return tot

for tag, L in LEVELS.items():
    H = (f"// Generated by gen_prov.py -- provisioning level '{tag}': {L['label']}\n"
         f"// {L['node']:.1f} W per decode node = DRAM 4 x {L['dram']:.2f} + logic {L['logic']:.2f} + PIC {P_PIC}\n"
         f"// Channels taken per-column from the performance table, NOT scaled uniformly:\n"
         f"// the I/O term falls with batch size while DRAM and compute rise.\n\n")
    a = write(f"pan_mem_{tag}.flp", H + "// TOP tier: xPU 300 W, HBM3 20 W (both constant), eight M3D-DRAM tiles.\n\n",
              parse("pan_mem.flp"),
              lambda nm: L['dram'] if nm.startswith("DRAM") else (P_XPU if nm == "XPU" else (P_HBM if nm == "HBM" else 0.0)))
    b = write(f"pan_logic_{tag}.flp", H + "// LOGIC DIE: NMP compute + DRAM controllers + EIC drivers.\n\n",
              parse("pan_logic.flp"), lambda nm: L['logic'] if nm.startswith("LOGIC") else 0.0)
    print(f"{tag}: mem tier {a:.2f} W, logic tier {b:.2f} W, PIC tier {3*P_PIC:.2f} W -> package {a+b+3*P_PIC:.2f} W")

base = open("pan-std.stk").read()
for tag, L in LEVELS.items():
    for cond, h, t in (("", 4.08e-8, 300), ("-735", 4.08e-8*0.735, 308), ("-575", 4.08e-8*0.575, 308)):
        name = f"pan-{tag}{cond}"
        s = base
        s = s.replace('"pan_mem.flp"', f'"pan_mem_{tag}.flp"').replace('"pan_logic.flp"', f'"pan_logic_{tag}.flp"')
        s = re.sub(r"heat transfer coefficient [\d.eE+-]+ ;", f"heat transfer coefficient {h:.4g} ;", s)
        s = re.sub(r"temperature \d+ ;", f"temperature {t} ;", s)
        s = re.sub(r"initial temperature [\d.]+ ;", f"initial temperature {float(t):.1f} ;", s)
        s = s.replace("outputs-pan/pan-std", f"outputs-pan/{name}").replace("pan-std.stk", f"{name}.stk")
        note = (f"// PROVISIONING LEVEL: {L['label']}, {L['node']:.1f} W per decode node, "
                f"package {P_XPU+P_HBM+P_PIC+2*(4*L['dram']+L['logic']+P_PIC):.1f} W.\n"
                f"// {'Warm loop: 35 C inlet, PG25-30 (h x{h/4.08e-8:g}). 45 C follows by exact +10 K offset.' if cond else 'Laboratory inlet 26.85 C, validated water plate.'}\n")
        s = s.replace("// ============================================================\n// pan-", note + "// ============================================================\n// pan-", 1)
        open(f"{name}.stk", "w").write(s)
print("\nWrote water, 0.735 and 0.575 workload/TDP stacks")
