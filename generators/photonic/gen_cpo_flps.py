#!/usr/bin/env python3
"""
gen_cpo_flps.py -- emit tier1 (2.5D / 3D), tier2, and PIC-plane floorplans for the
CPO comparison against Sheikh Sofla et al. Fully tiles the 40 x 30 mm canvas with
non-overlapping blocks (verified before writing).
"""
CL, CW = 40000, 30000

def bands(spec):
    """spec: list of (y0,y1,[(x0,x1,name,power), ...]) -> block list, auto-filling x gaps."""
    out = []
    for y0, y1, cols in spec:
        x = 0
        for x0, x1, name, p in sorted(cols):
            if x0 > x:
                out.append((f"FILL_{y0}_{x}", x, y0, x0 - x, y1 - y0, 0.0))
            out.append((name, x0, y0, x1 - x0, y1 - y0, p))
            x = x1
        if x < CL:
            out.append((f"FILL_{y0}_{x}", x, y0, CL - x, y1 - y0, 0.0))
    return out

def verify(blocks, label):
    for n, x, y, l, w, p in blocks:
        assert l > 0 and w > 0, f"{label}: {n} non-positive"
        assert 0 <= x and 0 <= y and x + l <= CL and y + w <= CW, f"{label}: {n} out of bounds"
        assert x % 100 == 0 and y % 100 == 0 and l % 100 == 0 and w % 100 == 0, f"{label}: {n} off grid"
    area = sum(l * w for _, _, _, l, w, _ in blocks)
    assert area == CL * CW, f"{label}: tiling covers {area} != {CL*CW}"
    for i in range(len(blocks)):
        for j in range(i + 1, len(blocks)):
            a, b = blocks[i], blocks[j]
            if not (a[1] + a[3] <= b[1] or b[1] + b[3] <= a[1] or
                    a[2] + a[4] <= b[2] or b[2] + b[4] <= a[2]):
                raise AssertionError(f"{label}: overlap {a[0]} / {b[0]}")
    return sum(p for *_, p in blocks)

def write(path, header, blocks):
    with open(path, "w") as f:
        f.write(header.rstrip() + "\n\n")
        for n, x, y, l, w, p in blocks:
            f.write(f"{n} :\n   position {x}, {y} ;\n   dimension {l}, {w} ;\n"
                    f"   power values {p} ;\n\n")

# ---------------- TIER 1 : compute (Si). EIC position is the ONLY difference ----
def tier1(eic_y0):
    return bands([
        (0, 6000, []),
        (6000, 14000, [(1000, 7000, "HBM_L1", 25.0), (8000, 26000, "GPU_A", 144.0),
                       (27000, 33000, "HBM_R1", 25.0)] +
                      ([(33500, 38500, "EIC", 20.0)] if eic_y0 == 6000 else [])),
        (14000, 14500, [(1000, 7000, "HBM_L1b", 0.0), (8000, 26000, "GPU_B", 9.0),
                        (27000, 33000, "HBM_R1b", 0.0)]),
        (14500, 15500, [(8000, 26000, "GPU_C", 18.0)]),
        (15500, 16000, [(1000, 7000, "HBM_L2b", 0.0), (8000, 26000, "GPU_D", 9.0),
                        (27000, 33000, "HBM_R2b", 0.0)]),
        (16000, 24000, [(1000, 7000, "HBM_L2", 25.0), (8000, 26000, "GPU_E", 144.0),
                        (27000, 33000, "HBM_R2", 25.0)] +
                       ([(33500, 38500, "EIC", 20.0)] if eic_y0 == 16000 else [])),
        (24000, 30000, []),
    ])

# ---------------- TIER 2 : CPU embedded beneath the GPU (Si) -------------------
tier2 = bands([
    (0, 11000, []),
    (11000, 19000, [(13000, 21000, "CPU", 80.0)]),
    (19000, 30000, []),
])

# ---------------- PIC PLANE : glass, region markers ----------------------------
pic = bands([
    (0, 16000, []),
    (16000, 17000, [(33500, 34000, "PIC_LASER", 0.30)]),
    (17000, 19000, [(33500, 38500, "PIC_WG", 0.0)]),
    (19000, 21000, [(35000, 37000, "PIC_RINGS", 0.20)]),
    (21000, 24000, [(33500, 38500, "PIC_BODY", 0.0)]),
    (24000, 30000, []),
])

H = "// AUTO-GENERATED by gen_cpo_flps.py -- do not hand-edit; regenerate instead.\n"
cases = [
    ("tier1_2p5d.flp", H + "// TIER 1 compute, 2.5D: EIC laterally offset 2 mm from the PIC footprint.", tier1(6000)),
    ("tier1_3d.flp",   H + "// TIER 1 compute, 3D: EIC directly ABOVE the PIC footprint.", tier1(16000)),
    ("tier2_cpu.flp",  H + "// TIER 2: CPU embedded beneath the GPU (identical in both configs).", tier2),
    ("pic_plane.flp",  H + "// PIC PLANE (glass). Powered: laser 0.3 W, ring bank 0.2 W.\n"
                           "// PIC_WG / PIC_BODY are 0 W REGION MARKERS -- their Tflp readout is the\n"
                           "// temperature routed waveguides actually see. Identical in both configs.", pic),
]
for path, hdr, blks in cases:
    tot = verify(blks, path)
    write(path, hdr, blks)
    print(f"  {path:18s} {len(blks):3d} blocks, tiling exact, sum = {tot:7.2f} W")
