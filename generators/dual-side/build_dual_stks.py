#!/usr/bin/env python3
"""build_dual_stks.py -- D1 (co-planar + bottom plate) and D2 (true dual-plate) stacks."""
import os
OUT = "outputs-dual"
H_VAL, PG30 = 4.08e-8, 0.735      # validated plate; PG30 derate (turbulent bound x0.60)
H_CHEAP = 2.0e-8                 # half-grade commodity secondary plate: labelled sensitivity

MATERIALS = """
material SILICON :
    thermal conductivity     1.30e-04 ;
    volumetric heat capacity 1.75e-12 ;
material TIM :
    thermal conductivity     4.00e-06 ;
    volumetric heat capacity 4.00e-12 ;
material COPPER :
    thermal conductivity     4.00e-04 ;
    volumetric heat capacity 3.45e-12 ;
material HYBRID_BOND :
    thermal conductivity     1.21e-04 ;
    volumetric heat capacity 2.14e-12 ;
material UBUMP_UF :
    thermal conductivity     2.00e-05 ;
    volumetric heat capacity 2.50e-12 ;
material GLASS :
    thermal conductivity     1.40e-06 ;
    volumetric heat capacity 1.60e-12 ;
material TGV_GLASS_COMPOSITE :
    thermal conductivity     1.00e-06, 1.00e-06, 7.9204e-05 ;
    volumetric heat capacity 1.96e-12 ;
"""

DIMS = """
dimensions :
    chip length 39600, width 31800 ;
    cell length 100,   width 100 ;
    non-uniform false ;
"""

LAYERS = """
layer CP_BASE_L :            // 2 mm Cu cold-plate base (PRIMARY). h is applied to its OUTER
    height   2000 ;          // face: the validated 4.08e-8 is the fins+coolant ABOVE this
    material COPPER ;        // base, referenced to the footprint -- not the whole plate.
layer CP_BASE2_L :           // 2 mm Cu base of the SECONDARY plate, mirrored construction
    height   2000 ;
    material COPPER ;
layer TIM_L :
    height   20 ;
    material TIM ;
layer HB_L :
    height   1 ;
    material HYBRID_BOND ;
layer UBUMP_L :
    height   40 ;
    material UBUMP_UF ;
layer IPOSER_TGV_L :
    height   110 ;
    material TGV_GLASS_COMPOSITE ;
layer IPOSER_CAV_L :
    height   100 ;
    material GLASS ;
layer IPOSER_CORE_L :
    height   150 ;
    material GLASS ;

die DIE_TOP_D :
    layer  145 SILICON ;
    source   5 SILICON ;
die DIE_BOT_D :
    source   5 SILICON ;
    layer   95 SILICON ;
die PIC_PLANE_D :
    source  20 GLASS ;
die DIE_MEM_D :              // D2: Mono3D DRAM, source on the face toward the glass
    source   5 SILICON ;
    layer   95 SILICON ;
die DIE_LOGIC_D :            // D2: Mono3D NMP logic
    source   5 SILICON ;
    layer   95 SILICON ;
"""

def sinks(h_top, h_bot, tref):
    s = f"""
top heat sink :
    heat transfer coefficient {h_top:.4g} ;
    temperature {tref} ;
"""
    if h_bot:
        s += f"""
// SECONDARY plate. A Robin condition on BOTH faces means both plates are fed fresh coolant
// at {tref} K -- i.e. PARALLEL plumbing, and twice the pump demand. A series feed (secondary
// inlet = primary outlet + rise) CANNOT be expressed this way; that needs the flow branch.
// GRAMMAR NOTE: verify 'bottom heat sink' against the 3D-ICE 4.0 grammar before trusting a
// run. If it is not supported, the fallback is a 4rm channel below CP_BASE2 using the
// calibrated 100/100/H=250 Cu geometry at high flow, whose Robin-equivalence we measured
// (-0.44 K on the concentrated die, +0.40 K on the diffuse one).
bottom heat sink :
    heat transfer coefficient {h_bot:.4g} ;
    temperature {tref} ;
"""
    return s

def outs(tag, blocks):
    o = f"""
solver :
    steady ;
    initial temperature {300.0} ;
    numofcores 12 ;

output :
"""
    for b in blocks:
        o += f'    Tflp( {b}, "{OUT}/{tag}_{b.lower()}_max.txt", maximum, final ) ;\n'
        o += f'    Tflp( {b}, "{OUT}/{tag}_{b.lower()}_avg.txt", average, final ) ;\n'
    o += f'    Tflp( PIC_PLANE, "{OUT}/{tag}_pic_min.txt", minimum, final ) ;\n'
    for b in blocks + ["CP_BASE", "CP_BASE2"]:
        o += f'    Tmap( {b}, "{OUT}/{tag}_{b.lower()}_tmap.txt", final ) ;\n'
    return o

def d1(tag, h_bot, h_top, tref, note):
    hdr = f"""// ============================================================
// {tag}.stk -- D1: CO-PLANAR BRIDGE + SECONDARY BOTTOM PLATE
// {note}
// Floorplans IDENTICAL to static-standard, so the ONLY change is that the adiabatic bottom
// is replaced by TIM + 2 mm Cu + a secondary plate. Everything else is the validated stack.
// WHAT THIS MEASURES: the secondary path runs through 270 um of glass (CAV 100 + PIC 20 +
// CORE 150) at k = 1.4e-6, i.e. 1.93e8 um^2K/W, against a top path of ~3.45e7 um^2K/W.
// Predicted bottom-side conductance ~15% of the top, so expect ~1-2.5 K on LOGIC0. If that
// is what comes out, D1 is the ARGUMENT AGAINST itself and motivates D2.
// Generated by build_dual_stks.py.
// ============================================================
"""
    stack = """
stack :
    layer   CP_BASE     CP_BASE_L ;
    layer   TIM_TOP     TIM_L ;
    die     DIE_TOP     DIE_TOP_D  floorplan "die_top_bridge.flp" ;
    layer   HB_IFACE    HB_L ;
    die     DIE_BOT     DIE_BOT_D  floorplan "die_bot_bridge.flp" ;
    layer   UBUMP       UBUMP_L ;
    layer   IPOSER_TGV  IPOSER_TGV_L ;
    layer   IPOSER_CAV  IPOSER_CAV_L ;
    die     PIC_PLANE   PIC_PLANE_D floorplan "pic_plane_bridge.flp" ;
    layer   IPOSER_CORE IPOSER_CORE_L ;
    layer   TIM_BOT     TIM_L ;
    layer   CP_BASE2    CP_BASE2_L ;
"""
    return hdr + MATERIALS + sinks(h_top, h_bot, tref) + DIMS + LAYERS + stack + outs(tag, ["DIE_TOP", "DIE_BOT", "PIC_PLANE"])

def d2(tag, h_bot, h_top, tref, note):
    hdr = f"""// ============================================================
// {tag}.stk -- D2: TRUE DUAL-PLATE, GLASS-SEPARATED (Tejinder's flagship)
// {note}
// primary plate | Cu base | TIM | xPU(+OPT_IO) | ubump | GLASS INTERPOSER (TGV + PIC plane)
//   | ubump | NMP logic | hybrid bond | Mono3D DRAM | TIM | Cu base | secondary plate
// Each plate owns ONE die with no glass in its path. The glass does triple duty: TGV
// routing, thermal separation between the tiers, and the optical waveguide plane. No signal
// crosses coolant: the electrical hub sits BETWEEN the dies, the coolers OUTSIDE them.
// Same canvas, same total power (405.27 W), same 270 um of glass as the co-planar rows, so
// the comparison is at equal plate area, equal power, equal glass.
// DIE ORDER: MEM0 (84.3 W/cm^2) faces the secondary plate, LOGIC0 (35.3 W/cm^2) faces the
// glass -- cooling follows power. Swap the two floorplan names to test the alternative.
// KEY READOUT: PIC_TGV max-min, the glass directly between the xPU and the memory tier.
// Generated by build_dual_stks.py.
// ============================================================
"""
    stack = """
stack :
    layer   CP_BASE     CP_BASE_L ;
    layer   TIM_TOP     TIM_L ;
    die     DIE_TOP     DIE_TOP_D   floorplan "die_xpu_dual.flp" ;
    layer   UBUMP       UBUMP_L ;
    layer   IPOSER_TGV  IPOSER_TGV_L ;
    layer   IPOSER_CAV  IPOSER_CAV_L ;
    die     PIC_PLANE   PIC_PLANE_D floorplan "pic_plane_dual.flp" ;
    layer   IPOSER_CORE IPOSER_CORE_L ;
    layer   UBUMP_BOT   UBUMP_L ;
    die     DIE_LOGIC   DIE_LOGIC_D floorplan "die_logic_dual.flp" ;
    layer   HB_IFACE    HB_L ;
    die     DIE_MEM     DIE_MEM_D   floorplan "die_mem_dual.flp" ;
    layer   TIM_BOT     TIM_L ;
    layer   CP_BASE2    CP_BASE2_L ;
"""
    return hdr + MATERIALS + sinks(h_top, h_bot, tref) + DIMS + LAYERS + stack + outs(tag, ["DIE_TOP", "DIE_LOGIC", "DIE_MEM", "PIC_PLANE"])

def main():
    os.makedirs("runs", exist_ok=True)
    f = {}
    f["d1-standard"] = d1("d1-standard", H_VAL, H_VAL, 300, "Water, 300 K. Compare directly to static-standard (LOGIC0 329.009 K).")
    f["d1-warm"]     = d1("d1-warm", H_VAL*PG30, H_VAL*PG30, 308, "PG30 at 35 C. Compare to static-warm (LOGIC0 340.595 K).")
    f["d1-cheap"]    = d1("d1-cheap", H_CHEAP, H_VAL, 300, "Secondary plate at HALF grade (2.0e-8). Sensitivity: how much of D1's gain survives a commodity bottom plate.")
    f["d2-standard"] = d2("d2-standard", H_VAL, H_VAL, 300, "Water, 300 K. The row to compare against static-standard at equal power and plate area.")
    f["d2-warm"]     = d2("d2-warm", H_VAL*PG30, H_VAL*PG30, 308, "PG30 at 35 C. The headline dual-plate number.")
    f["d2-cheap"]    = d2("d2-cheap", H_CHEAP, H_VAL, 300, "Secondary plate at HALF grade (2.0e-8): tests Tejinder's 'memory does not need liquid cooling'.")
    f["d2-noplate"]  = d2("d2-noplate", None, H_VAL, 300, "CONTROL: secondary plate REMOVED (adiabatic bottom). Isolates exactly what the second plate buys in D2.")
    for t, txt in f.items():
        open(f"runs/{t}.stk", "w").write(txt)
    print(f"wrote {len(f)} stacks to runs/")

if __name__ == "__main__":
    main()
