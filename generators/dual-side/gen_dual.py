#!/usr/bin/env python3
"""
gen_dual.py -- floorplans + stacks for the two bottom-cooled variants of the co-planar
bridge package.

  D1  co-planar + bottom plate : IDENTICAL floorplans to static-standard. The only change is
                                 that the adiabatic bottom is replaced by TIM + 2 mm Cu base
                                 + a secondary plate. Measures what a second plate buys when
                                 its path runs through 270 um of glass.
  D2  true dual-plate          : xPU (+OPT_IO) alone on the top tier against the primary
                                 plate; the Mono3D stack moved BELOW the glass, in direct
                                 contact with the secondary plate. Each plate owns one die
                                 with no glass in its path; the glass is routing + isolation
                                 + optical fabric between them.

Both keep the 39600 x 31800 canvas, the 100 um grid, and total glass thickness 270 um, so
every row is comparable at equal plate area, equal power, equal glass.
"""
CX, CY, GRID = 39600, 31800, 100
P_GPU, P_MEM, P_LOGIC, P_OPT = 230.0, 102.0, 42.67, 30.6

# ---- co-planar (D1) geometry: unchanged from static-standard ----
C_MEM = (2000, 10400, 11000, 11000)
C_OPT = (15000, 2000, 1200, 27800)
C_GPU = (16200, 2000, 21400, 27800)
C_COMB, C_ROUTE = (0, 15400, 400, 400), (400, 15400, 12600, 400)
C_BRIDGE = (13000, 10400, 2000, 11000)
C_MRR = (15000, 10400, 1200, 11000)
C_WGS, C_WGN = (13000, 2000, 3200, 8400), (13000, 21400, 3200, 8400)

# ---- D2 geometry: xPU centred on the plate, Mono3D centred beneath it ----
D_OPT = (8500, 2000, 1200, 27800)
D_GPU = (9700, 2000, 21400, 27800)          # same area as C_GPU
D_MEM = (14300, 10400, 11000, 11000)        # centred on the canvas, under D_GPU
D_COMB, D_ROUTE = (0, 15400, 400, 400), (400, 15400, 8100, 400)
D_MRR = (8500, 2000, 1200, 27800)           # under OPT_IO
D_TGV = (14300, 10400, 11000, 11000)        # glass between xPU and Mono3D: isolation readout


def tile(actives):
    ys = sorted({0, CY} | {a[2] for a in actives} | {a[2] + a[4] for a in actives})
    for a in actives:
        for y0, y1 in zip(ys, ys[1:]):
            inter = max(0, min(a[2] + a[4], y1) - max(a[2], y0))
            assert inter in (0, y1 - y0), f"{a[0]} straddles band {y0}-{y1}"
    out, n = [], 0
    for y0, y1 in zip(ys, ys[1:]):
        row = sorted([a for a in actives if a[2] <= y0 and a[2] + a[4] >= y1], key=lambda a: a[1])
        x = 0
        for a in row:
            if a[1] > x:
                out.append((f"FILL_{n}", x, y0, a[1] - x, y1 - y0, 0.0)); n += 1
            x = a[1] + a[3]
        if x < CX:
            out.append((f"FILL_{n}", x, y0, CX - x, y1 - y0, 0.0)); n += 1
    return out + list(actives)


def check(blocks, p_expect, label):
    area = 0
    for name, x, y, w, h, p in blocks:
        assert x >= 0 and y >= 0 and x + w <= CX and y + h <= CY, f"{label}/{name} out of bounds"
        assert w > 0 and h > 0, f"{label}/{name} degenerate"
        for v in (x, y, w, h):
            assert v % GRID == 0, f"{label}/{name} off grid: {v}"
        area += w * h
    for i, a in enumerate(blocks):
        for b in blocks[i + 1:]:
            if a[1] < b[1] + b[3] and b[1] < a[1] + a[3] and a[2] < b[2] + b[4] and b[2] < a[2] + a[4]:
                raise AssertionError(f"{label}: overlap {a[0]} / {b[0]}")
    assert area == CX * CY, f"{label}: tiling gap {area} != {CX*CY}"
    tot = sum(b[5] for b in blocks)
    assert abs(tot - p_expect) < 1e-6, f"{label}: power {tot} != {p_expect}"


def write(path, header, blocks, p_expect):
    check(blocks, p_expect, path)
    with open(path, "w") as f:
        f.write(header)
        for name, x, y, w, h, p in blocks:
            f.write(f"{name} :\n    position  {x}, {y} ;\n    dimension {w}, {h} ;\n    power values {p:g} ;\n\n")


HDR = "// Generated by gen_dual.py -- regenerate, do not hand-edit.\n\n"

def main():
    # ================= D1: same floorplans as static-standard, comb already 0 W ==========
    top = tile([("MEM0",) + C_MEM + (P_MEM,), ("OPT_IO",) + C_OPT + (P_OPT,), ("GPU0",) + C_GPU + (P_GPU,)])
    bot = [(("LOGIC0" if n == "MEM0" else ("FILL_UNDER_" + n if n in ("OPT_IO", "GPU0") else n)),
            x, y, w, h, (P_LOGIC if n == "MEM0" else 0.0)) for n, x, y, w, h, p in top]
    pic = tile([("COMB_SRC",) + C_COMB + (0.0,), ("PIC_ROUTE",) + C_ROUTE + (0.0,),
                ("BRIDGE",) + C_BRIDGE + (0.0,), ("PIC_MRR",) + C_MRR + (0.0,),
                ("PIC_WG_S",) + C_WGS + (0.0,), ("PIC_WG_N",) + C_WGN + (0.0,)])
    write("die_top_bridge.flp", "// die_top_bridge.flp -- co-planar top tier (D1). Identical to the\n"
          "// static-standard floorplan: MEM0 102 W, OPT_IO 30.6 W, GPU0 230 W (38.66 W/cm^2).\n" + HDR,
          top, P_MEM + P_OPT + P_GPU)
    write("die_bot_bridge.flp", "// die_bot_bridge.flp -- co-planar bottom tier (D1). LOGIC0 42.67 W under MEM0.\n"
          "// Block boundaries identical to die_top_bridge.flp.\n" + HDR, bot, P_LOGIC)
    write("pic_plane_bridge.flp", "// pic_plane_bridge.flp -- 20 um glass readout plane (D1). ALL BLOCKS 0 W.\n"
          "// COMB_SRC is a zero-power marker for externally generated, edge-injected WDM carriers;\n"
          "// Hsueh Fig. 9's 300 mW is optical pump input and is not package-local heat. (An earlier\n"
          "// run with it as 0.3 W of embedded dissipation reached 161 C at 448 K/W -- retained as a\n"
          "// labelled result justifying edge injection.)\n" + HDR, pic, 0.0)

    # ================= D2: xPU on top, Mono3D below the glass ==========================
    d_top = tile([("OPT_IO",) + D_OPT + (P_OPT,), ("GPU0",) + D_GPU + (P_GPU,)])
    d_mem = tile([("MEM0",) + D_MEM + (P_MEM,)])
    d_log = [(("LOGIC0" if n == "MEM0" else n), x, y, w, h, (P_LOGIC if n == "MEM0" else 0.0))
             for n, x, y, w, h, p in d_mem]
    d_pic = tile([("COMB_SRC",) + D_COMB + (0.0,), ("PIC_ROUTE",) + D_ROUTE + (0.0,),
                  ("PIC_MRR",) + D_MRR + (0.0,), ("PIC_TGV",) + D_TGV + (0.0,)])
    write("die_xpu_dual.flp",
          "// die_xpu_dual.flp -- D2 TOP tier: xPU + OPT_IO ALONE against the primary plate.\n"
          "// GPU0 21400x27800 = 594.92 mm^2 at 230 W = 38.66 W/cm^2 -- same area and density as the\n"
          "// co-planar rows, but CENTRED so the xPU uses the full primary plate.\n"
          "// OPT_IO 1200x27800 = 33.36 mm^2 at 30.6 W = 0.917 W/mm^2, on the xPU's west edge above\n"
          "// the MRR bank (transceivers ride the best-cooled die).\n" + HDR, d_top, P_GPU + P_OPT)
    write("die_mem_dual.flp",
          "// die_mem_dual.flp -- D2: Mono3D DRAM die, BELOW the glass, centred under the xPU.\n"
          "// MEM0 11x11 mm at 102 W = 84.3 W/cm^2. This die faces the SECONDARY plate side.\n" + HDR,
          d_mem, P_MEM)
    write("die_logic_dual.flp",
          "// die_logic_dual.flp -- D2: Mono3D NMP logic die, hybrid-bonded to die_mem_dual.\n"
          "// LOGIC0 42.67 W = 35.3 W/cm^2. Sits between MEM0 and the glass.\n"
          "// DEFAULT ORDER: the higher-flux die (MEM0, 84.3 W/cm^2) is nearest the secondary plate.\n"
          "// To test the alternative, swap the two floorplan names in the stack -- our own vertical\n"
          "// study says < 1 K, and this run measures it.\n" + HDR, d_log, P_LOGIC)
    write("pic_plane_dual.flp",
          "// pic_plane_dual.flp -- D2 glass readout plane. ALL BLOCKS 0 W.\n"
          "//   PIC_ROUTE  comb -> MRR lane, 400 um wide\n"
          "//   PIC_MRR    under OPT_IO: ring modulators / detectors\n"
          "//   PIC_TGV    the glass DIRECTLY between the xPU and the Mono3D stack. Its max-min is\n"
          "//              the isolation readout: how much of the 230 W die the memory tier sees.\n" + HDR,
          d_pic, 0.0)
    print("OK: 8 floorplans written; tiling / overlap / bounds / grid / power all asserted")
    print(f"  D1 top {P_MEM+P_OPT+P_GPU:.2f} W, bot {P_LOGIC} W")
    print(f"  D2 top {P_GPU+P_OPT:.2f} W, mem {P_MEM} W, logic {P_LOGIC} W; total {P_GPU+P_OPT+P_MEM+P_LOGIC:.2f} W")

if __name__ == "__main__":
    main()
